import torch
import torch.nn as nn
from typing import Tuple


class PartialSharedHead(nn.Module):
    """
    Partially-shared prediction head: a base MLP shared by all measurements plus a
    per-measurement low-rank (LoRA-style) weight delta and bias delta, generated by a
    hypernetwork from the measurement's conditioning embedding.

    MLP structure:
      - num_head_layers == 1 : (echo_dim -> 1)                     [hypernet 2 only]
      - num_head_layers > 1  : (echo_dim -> echo_dim -> act) x (L-1) then (echo_dim -> 1)
                                [hypernet 1 for intermediate layers, hypernet 2 for final]

    Hypernet 1 (intermediate layers, echo_dim -> echo_dim):
      - h1w: weight head producing the LoRA factors A (d x r) and B (r x d); size variants
             L: A and B generated in a single pass (output 2*r*d)
             M: A and B generated in two passes, distinguished by a learned A/B embedding
             S: every rank-1 column/row generated in its own pass (2*r passes), distinguished
                by learned A/B and rank embeddings
             conditioned on: measurement embedding + head-layer index embedding
      - h1b: bias head; conditioned on: measurement embedding + head-layer index embedding

    Hypernet 2 (final layer, echo_dim -> 1):
      - h2w: weight head producing a full-rank delta added to base_W_final
      - h2b: bias head
      conditioned on: measurement embedding

    When num_head_layers > 1, hypernet 1 and hypernet 2 share the same body
    (h1_body is h2_body); the four output heads stay separate.

    h1b, h2w and h2b are zero-initialised. h1w has a zero weight and a small uniform
    bias (for L only on the B factor, so that the L delta starts at exactly zero).
    """

    def __init__(
        self,
        echo_dim: int,
        cond_dim: int,
        num_head_layers: int = 1,
        head_dropout: float = 0.0,
        lora_rank: int = 8,
        lora_alpha: float = 16.0,
        hyper_hidden: int = 128,
        hypernet_size: str = "L",
    ) -> None:
        super().__init__()
        assert num_head_layers >= 1
        self.echo_dim = echo_dim
        self.num_head_layers = num_head_layers
        self.lora_rank = lora_rank
        self.lora_scale = lora_alpha / lora_rank
        self.hypernet_size = hypernet_size

        n_inter = num_head_layers - 1

        # --- Base MLP parameters ---
        self.base_W_inter = nn.ParameterList(
            [nn.Parameter(torch.empty(echo_dim, echo_dim)) for _ in range(n_inter)]
        )
        self.base_b_inter = nn.ParameterList(
            [nn.Parameter(torch.zeros(echo_dim)) for _ in range(n_inter)]
        )
        for W in self.base_W_inter:
            nn.init.kaiming_uniform_(W, a=5 ** 0.5)

        self.base_W_final = nn.Parameter(torch.empty(1, echo_dim))
        self.base_b_final = nn.Parameter(torch.zeros(1))
        nn.init.kaiming_uniform_(self.base_W_final, a=5 ** 0.5)

        self.activation = nn.GELU()
        self.dropout = nn.Dropout(p=head_dropout) if head_dropout > 0.0 else nn.Identity()

        # --- Hypernet 1: intermediate layers ---
        if n_inter > 0:
            self.layer_idx_emb = nn.Embedding(n_inter, cond_dim)
            self.layer_idx_emb_norm = nn.LayerNorm(cond_dim)

            if hypernet_size == "L":
                h1w_out = lora_rank * (2 * echo_dim)
            elif hypernet_size == "M":
                h1w_out = lora_rank * echo_dim
            elif hypernet_size == "S":
                h1w_out = echo_dim
            else:
                raise ValueError(f"hypernet_size must be 'L', 'M', or 'S', got {hypernet_size!r}")

            self.h1_body = self._make_body(cond_dim, hyper_hidden)
            self.h1w_head = nn.Linear(cond_dim, h1w_out)
            self._init_h1w_head(echo_dim, lora_rank, hypernet_size)

            if hypernet_size in ("M", "S"):
                self.ab_emb = nn.Parameter(torch.normal(0, 1, size=(2, cond_dim)))
                self.ab_emb_norm = nn.LayerNorm(cond_dim)
            if hypernet_size == "S":
                self.rank_emb = nn.Parameter(torch.normal(0, 1, size=(lora_rank, cond_dim)))
                self.rank_emb_norm = nn.LayerNorm(cond_dim)

            self.h1b_head = nn.Linear(cond_dim, echo_dim)
            nn.init.zeros_(self.h1b_head.weight)
            nn.init.zeros_(self.h1b_head.bias)

        # --- Hypernet 2: final layer ---
        if n_inter > 0:
            self.h2_body = self.h1_body  # shared body; PyTorch counts params once
        else:
            self.h2_body = self._make_body(cond_dim, hyper_hidden)
        self.h2w_head = nn.Linear(cond_dim, echo_dim)
        nn.init.zeros_(self.h2w_head.weight)
        nn.init.zeros_(self.h2w_head.bias)

        self.h2b_head = nn.Linear(cond_dim, 1)
        nn.init.zeros_(self.h2b_head.weight)
        nn.init.zeros_(self.h2b_head.bias)

    @staticmethod
    def _make_body(cond_dim: int, hyper_hidden: int) -> nn.Sequential:
        return nn.Sequential(
            nn.Linear(cond_dim, hyper_hidden),
            nn.GELU(),
            nn.Dropout(p=0.05, inplace=False),
            nn.Linear(hyper_hidden, cond_dim),
            nn.GELU(),
        )

    def _init_h1w_head(self, echo_dim: int, lora_rank: int, hypernet_size: str) -> None:
        nn.init.zeros_(self.h1w_head.weight)
        with torch.no_grad():
            bias = self.h1w_head.bias
            if hypernet_size == "L":
                n_A = echo_dim * lora_rank
                bias[:n_A].zero_()
                bias[n_A:].uniform_(-1.0 / echo_dim, 1.0 / echo_dim)
            elif hypernet_size == "M":
                bias.uniform_(-1.0 / ((2 ** 0.5) * echo_dim), 1.0 / ((2 ** 0.5) * echo_dim))
            else:  # "S"
                bias.uniform_(
                    -1.0 / (((lora_rank * 2) ** 0.5) * echo_dim),
                    1.0 / (((lora_rank * 2) ** 0.5) * echo_dim),
                )

    def _h1_lora_weights(self, cond: torch.Tensor, li: int) -> Tuple[torch.Tensor, torch.Tensor]:
        """Produce LoRA A (N, d, r) and B (N, r, d) for intermediate layer li."""
        N, d, r = cond.shape[0], self.echo_dim, self.lora_rank
        li_emb = self.layer_idx_emb_norm(self.layer_idx_emb(cond.new_tensor(li, dtype=torch.long)))  # (cond_dim,)
        c = cond + li_emb.unsqueeze(0)  # (N, cond_dim)

        if self.hypernet_size == "L":
            h = self.h1_body(c) + c                            # (N, cond_dim)
            p = self.h1w_head(h)                               # (N, 2*r*d)
            A = p[:, :(d * r)].reshape(N, d, r)               # (N, d, r)
            B = p[:, (d * r):].reshape(N, r, d)               # (N, r, d)
        elif self.hypernet_size == "M":
            ab_c = c.unsqueeze(1) + self.ab_emb_norm(self.ab_emb.unsqueeze(0))  # (N, 2, cond_dim)
            flat = ab_c.reshape(N * 2, -1)                                        # (N*2, cond_dim)
            h    = self.h1_body(flat) + flat                                      # (N*2, cond_dim)
            out  = self.h1w_head(h).reshape(N, 2, r, d)                          # (N, 2, r, d)
            A    = out[:, 0].permute(0, 2, 1)                                     # (N, d, r)
            B    = out[:, 1]                                                       # (N, r, d)
        else:  # "S"
            ab0  = self.ab_emb_norm(self.ab_emb[0])   # (cond_dim,)
            ab1  = self.ab_emb_norm(self.ab_emb[1])   # (cond_dim,)
            re   = self.rank_emb_norm(self.rank_emb)   # (r, cond_dim)
            cA   = c.unsqueeze(1) + ab0 + re           # (N, r, cond_dim)
            cB   = c.unsqueeze(1) + ab1 + re           # (N, r, cond_dim)
            flat = torch.cat([cA, cB], dim=1).reshape(N * 2 * r, -1)  # (N*2*r, cond_dim)
            h    = self.h1_body(flat) + flat                            # (N*2*r, cond_dim)
            sl   = self.h1w_head(h).reshape(N, 2 * r, d)               # (N, 2*r, d)
            A    = sl[:, :r].permute(0, 2, 1)                           # (N, d, r)
            B    = sl[:, r:]                                             # (N, r, d)

        return A, B

    def _h1_bias(self, cond: torch.Tensor, li: int) -> torch.Tensor:
        """Produce per-condition bias (N, echo_dim) for intermediate layer li."""
        li_emb = self.layer_idx_emb_norm(self.layer_idx_emb(cond.new_tensor(li, dtype=torch.long)))
        c = cond + li_emb.unsqueeze(0)   # (N, cond_dim)
        h = self.h1_body(c) + c           # (N, cond_dim)
        return self.h1b_head(h)           # (N, echo_dim)

    def _h2_weight(self, cond: torch.Tensor) -> torch.Tensor:
        """Produce A delta (N, 1, echo_dim) for final layer."""
        h = self.h2_body(cond) + cond        # (N, cond_dim)
        return self.h2w_head(h).unsqueeze(1)  # (N, 1, echo_dim)

    def _h2_bias(self, cond: torch.Tensor) -> torch.Tensor:
        """Produce per-condition bias (N, 1) for final layer."""
        h = self.h2_body(cond) + cond    # (N, cond_dim)
        return self.h2b_head(h)           # (N, 1)

    def _apply_lora_mlp(self, cond: torch.Tensor, x: torch.Tensor) -> torch.Tensor:
        """
        Args:
            cond: (N, cond_dim)
            x:    (N, B, echo_dim)
        Returns:
            (N, B)
        """
        out = x

        for li in range(self.num_head_layers - 1):
            A, B        = self._h1_lora_weights(cond, li)           # (N,d,r), (N,r,d)
            bias_delta  = self._h1_bias(cond, li)                    # (N, d)

            base  = torch.einsum("oi,nbi->nbo", self.base_W_inter[li], out)  # (N, B, d)
            xB    = torch.einsum("nri,nbi->nbr", B, out)                      # (N, B, r)
            delta = torch.einsum("nor,nbr->nbo", A, xB)                       # (N, B, d)
            bias  = self.base_b_inter[li].view(1, 1, -1) + bias_delta.unsqueeze(1)  # (N, 1, d)

            out = self.dropout(self.activation(base + self.lora_scale * delta + bias))

        A_final    = self._h2_weight(cond)   # (N, 1, echo_dim)
        bias_final = self._h2_bias(cond)     # (N, 1)

        base_f  = torch.einsum("oi,nbi->nbo", self.base_W_final, out)  # (N, B, 1)
        delta_f = torch.einsum("noi,nbi->nbo", A_final, out)            # (N, B, 1)
        bias_f  = self.base_b_final.view(1, 1, -1) + bias_final.unsqueeze(1)  # (N, 1, 1)

        out = base_f + delta_f + bias_f

        return out.squeeze(-1)  # (N, B)

    def forward(self, feature_tokens: torch.Tensor, cond: torch.Tensor) -> torch.Tensor:
        """
        Args:
            feature_tokens: (B, N, echo_dim)
            cond:           (N, cond_dim)
        Returns:
            (B, N)
        """
        return self._apply_lora_mlp(
            cond, feature_tokens.transpose(0, 1)
        ).transpose(0, 1)
