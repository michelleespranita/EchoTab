from typing import Optional

import torch
import torch.nn as nn

from .IndependentHeads import IndependentHeads
from .PartialSharedHead import PartialSharedHead
from .SharedHead import SharedHead

HEAD_TYPES = ("independent", "shared", "partial_shared")


class PredictionHead(nn.Module):
    """
    Predicts one scalar value per measurement from its TabDecoder bottleneck token.

    head_type:
      "independent"    — IndependentHeads: one separate MLP per measurement.
      "shared"         — SharedHead: one MLP shared by all measurements, unconditioned.
      "partial_shared" — PartialSharedHead: a shared base MLP plus a per-measurement
                         low-rank weight delta generated by a hypernetwork from the
                         measurement's embedding (TabularBranch.conditioning_emb()).
                         The embedding is detached, so the head does not backpropagate
                         into it; it is optionally projected to cond_proj_dim first.
    """

    def __init__(
        self,
        head_type: str,
        echo_dim: int,
        num_features: int,
        num_head_layers: int = 1,
        head_dropout: float = 0.0,
        cond_dim: Optional[int] = None,
        cond_proj_dim: Optional[int] = None,
        lora_rank: int = 8,
        lora_alpha: float = 16.0,
        hyper_hidden: int = 128,
        hypernet_size: str = "L",
    ) -> None:
        super().__init__()
        if head_type not in HEAD_TYPES:
            raise ValueError(f"head_type must be one of {HEAD_TYPES}, got {head_type!r}")
        self.head_type = head_type

        if head_type == "independent":
            self.head = IndependentHeads(echo_dim, num_features, num_head_layers, head_dropout)
        elif head_type == "shared":
            self.head = SharedHead(echo_dim, num_head_layers, head_dropout)
        else:
            if cond_dim is None:
                raise ValueError("cond_dim is required for head_type='partial_shared'")
            if cond_proj_dim is not None and cond_proj_dim != cond_dim:
                self.cond_projection = nn.Sequential(
                    nn.Linear(cond_dim, cond_proj_dim),
                    nn.LayerNorm(cond_proj_dim),
                )
                cond_dim = cond_proj_dim
            else:
                self.cond_projection = nn.Identity()

            self.head = PartialSharedHead(
                echo_dim, cond_dim, num_head_layers, head_dropout,
                lora_rank, lora_alpha, hyper_hidden, hypernet_size,
            )

    @property
    def needs_conditioning(self) -> bool:
        return self.head_type == "partial_shared"

    def forward(self, bottleneck: torch.Tensor, cond_emb: Optional[torch.Tensor] = None) -> torch.Tensor:
        """
        Args:
            bottleneck: (B, N, echo_dim) TabDecoder output tokens.
            cond_emb:   (N, cond_dim) per-measurement embeddings; required for
                        head_type='partial_shared', ignored otherwise.
        Returns:
            (B, N) — one prediction per measurement.
        """
        if not self.needs_conditioning:
            return self.head(bottleneck)

        if cond_emb is None:
            raise ValueError("cond_emb must be provided for head_type='partial_shared'")
        cond = self.cond_projection(cond_emb.detach())  # (N, cond_dim)
        return self.head(bottleneck, cond)
